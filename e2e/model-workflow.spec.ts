import { test, expect } from '@playwright/test';
import { readFileSync, mkdtempSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { config, stateDir } from '../scripts/config.mjs';
import type { CreateProjectResponse, Project } from '../shared/contracts.js';
const settings = config();
const users = JSON.parse(readFileSync(resolve(stateDir, 'credentials.json'), 'utf8')).users;
const owner = users.find((user: { username: string }) => user.username === 'ada');
const headers = { Origin: settings.appOrigin };

test('owner workspace, optional save note, history restore and real Git preservation', async ({ page }) => {
  test.setTimeout(60000);
  await page.request.post('/api/session', { headers, data: owner });
  const created = await page.request.post('/api/projects', { headers, data: { requestId: randomUUID(), templateId: 'worker', title: `Simple workflow ${randomUUID().slice(0, 8)}`, visibility: 'public' } });
  expect(created.status()).toBe(201);
  const model = await created.json() as CreateProjectResponse;
  await page.goto(`/#/project/${model.project.id}`);
  await expect(page.frameLocator('iframe').locator('#status')).toHaveText('Ready');
  await expect(page.locator('.code-console')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Git details', exact: true })).toBeVisible();
  await page.getByRole('treeitem', { name: 'README.md', exact: false }).click();
  const editor = page.getByLabel('Source code', { exact: true });
  await editor.click(); await page.keyboard.press('ControlOrMeta+A'); await page.keyboard.insertText('# A saved experiment\n');
  await expect(page.getByLabel('What changed?', { exact: true })).toHaveValue('');
  const savedResponse = page.waitForResponse(response => response.url().endsWith('/draft/save') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save version', exact: true }).click();
  const saved = await savedResponse; expect(saved.status()).toBe(201);
  const savedCommit = (await saved.json()).commit;
  await page.getByRole('button', { name: 'History', exact: true }).click();
  await expect(page.locator('.history-entry').first()).toContainText('Update README.md');
  await page.locator(`.history-entry[data-commit="${model.commit}"] .history-select`).click();
  await expect(page.locator('.version-context')).toContainText('Earlier version');
  await page.getByRole('button', { name: 'Restore this version', exact: true }).click();
  const restoredResponse = page.waitForResponse(response => response.url().endsWith('/restores'));
  await page.getByRole('button', { name: 'Restore version', exact: true }).click();
  const restored = await restoredResponse; expect(restored.status()).toBe(201);
  const restoredCommit = (await restored.json()).commit;
  const clone = mkdtempSync(resolve(stateDir, 'workflow-git-'));
  try {
    const env = { ...process.env, GIT_TERMINAL_PROMPT: '0', GIT_CONFIG_COUNT: '1', GIT_CONFIG_KEY_0: 'http.extraHeader', GIT_CONFIG_VALUE_0: `Authorization: Basic ${Buffer.from(`${owner.username}:${owner.password}`).toString('base64')}` };
    execFileSync('git', ['clone', '--quiet', '--bare', `${settings.forgejoUrl}/${model.project.forgejoOwner}/${model.project.forgejoRepo}.git`, clone], { env });
    const git = (...args: string[]) => execFileSync('git', ['--git-dir', clone, ...args], { env, encoding: 'utf8' }).trim();
    expect(git('rev-parse', 'HEAD')).toBe(restoredCommit);
    expect(git('rev-parse', 'HEAD^')).toBe(savedCommit);
    expect(git('rev-parse', 'HEAD^{tree}')).toBe(git('rev-parse', `${model.commit}^{tree}`));
    expect(git('show', `${savedCommit}:README.md`)).toBe('# A saved experiment');
  } finally { rmSync(clone, { recursive: true, force: true }); }
  const stale = await page.request.post(`/api/projects/${model.project.id}/restores`, { headers, data: { ref: model.ref, expectedCommit: savedCommit, sourceCommit: model.commit } });
  expect(stale.status()).toBe(409);
  expect((await (await page.request.get(`/api/projects/${model.project.id}/tree`)).json()).commit).toBe(restoredCommit);
  await page.request.post('/api/session', { headers, data: users.find((user: { username: string }) => user.username === 'ben') });
  expect((await page.request.post(`/api/projects/${model.project.id}/restores`, { headers, data: { ref: model.ref, expectedCommit: restoredCommit, sourceCommit: savedCommit } })).status()).toBe(403);
});

test('library detail leads to examples and installs into a chosen model with simple defaults', async ({ page }) => {
  test.setTimeout(120000);
  await page.request.post('/api/session', { headers, data: owner });
  const model = await (await page.request.post('/api/projects', { headers, data: { requestId: randomUUID(), templateId: 'worker', title: `Library destination ${randomUUID().slice(0, 8)}`, visibility: 'private' } })).json() as CreateProjectResponse;
  const catalog = (await (await page.request.get('/api/projects')).json()).projects as Project[];
  const library = catalog.find(item => item.forgejoRepo === 'agent-grid')!;
  await page.goto(`/#/project/${library.id}`);
  await page.getByRole('button', { name: 'Examples', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('link', { name: /Grid walkers/ })).toBeVisible({ timeout: 60000 });
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.locator('.library-use-actions').getByRole('button', { name: 'Add to artifact', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Artifact', { exact: true }).selectOption(model.project.id);
  await page.getByRole('link', { name: 'Continue', exact: true }).click();
  const dialog = page.locator('dialog[open]');
  await expect(dialog.getByLabel('Library version', { exact: true })).toBeEnabled();
  await expect(dialog.getByLabel('Destination directory', { exact: true })).toBeHidden();
  const response = page.waitForResponse(response => response.url().endsWith('/libraries') && response.request().method() === 'POST');
  await dialog.getByRole('button', { name: 'Add to artifact', exact: true }).click();
  expect((await response).status()).toBe(200);
  expect((await (await page.request.get(`/api/projects/${model.project.id}/tree`)).json()).commit).toBe(model.commit);
  await expect(page.locator('.libraries-panel').getByRole('link', { name: 'Agent grid', exact: true })).toBeVisible();
  await expect(page.locator('.libraries-panel').getByRole('link', { name: 'Browser kit', exact: true })).toBeVisible();
  await expect(page.locator('dialog[open]')).toHaveCount(0);
});
